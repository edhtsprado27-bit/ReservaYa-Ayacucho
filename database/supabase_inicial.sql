CREATE OR REPLACE FUNCTION fn_refresh_venue_rating()
RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_venue uuid := COALESCE(NEW.venue_id, OLD.venue_id);
BEGIN
  UPDATE venues v
  SET rating_avg   = COALESCE(s.avg_rating, 0),
      rating_count = COALESCE(s.cnt, 0)
  FROM (
    SELECT ROUND(AVG(rating)::numeric, 2) AS avg_rating, COUNT(*) AS cnt
    FROM reviews
    WHERE venue_id = v_venue AND is_visible

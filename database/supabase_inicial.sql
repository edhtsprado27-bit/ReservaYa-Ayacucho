-- ---------------------------------------------------------------------
-- 2. *** GARANTIA ANTI DOBLE RESERVA ***
--    Dos reservas "activas" de la MISMA cancha no pueden tener rangos
--    que se intersecten (&&). Lo verifica PostgreSQL de forma atomica,
--    incluso con 2 transacciones concurrentes en el mismo milisegundo.
--    Si choca -> SQLSTATE 23P01 (exclusion_violation).
--    cancelled / expired quedan fuera del indice => liberan el horario.
-- ---------------------------------------------------------------------
ALTER TABLE bookings
  ADD CONSTRAINT bookings_no_overlap
  EXCLUDE USING gist (court_id WITH =, period WITH &&)
  WHERE (status NOT IN ('cancelled', 'expired'));

-- Bloqueos de mantenimiento tampoco se solapan entre si
ALTER TABLE court_blackouts
  ADD CONSTRAINT blackouts_valid_range CHECK (ends_at > starts_at),
  ADD CONSTRAINT blackouts_no_overlap
  EXCLUDE USING gist (court_id WITH =, tstzrange(starts_at, ends_at, '[)') WITH &&);

-- ---------------------------------------------------------------------
-- 3. Validacion de negocio: cancha activa, local aprobado, dentro del
--    horario de atencion, sin blackout y no en el pasado.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_validate_booking()
RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_local_start timestamp := NEW.starts_at AT TIME ZONE 'America/Lima';
  v_local_end   timestamp := NEW.ends_at   AT TIME ZONE 'America/Lima';
  v_day_start   timestamp := date_trunc('day', v_local_start);
  v_dow         smallint  := EXTRACT(DOW FROM v_local_start);
BEGIN
  -- Reservas inactivas no se validan
  IF NEW.status IN ('cancelled', 'expired') THEN
    RETURN NEW;
  END IF;

  -- En UPDATE solo se revalida si cambia cancha/horario o si se "reactiva"
  IF TG_OP = 'UPDATE'
     AND NEW.court_id  = OLD.court_id
     AND NEW.starts_at = OLD.starts_at
     AND NEW.ends_at   = OLD.ends_at
     AND OLD.status NOT IN ('cancelled', 'expired') THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'INSERT' AND NEW.source <> 'owner_manual'
     AND NEW.starts_at < now() THEN
    RAISE EXCEPTION 'BOOKING_IN_PAST' USING ERRCODE = 'P0001';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM courts c
    JOIN venues v ON v.id = c.venue_id
    WHERE c.id = NEW.court_id
      AND c.status = 'active'
      AND v.status = 'approved'
  ) THEN
    RAISE EXCEPTION 'COURT_NOT_BOOKABLE' USING ERRCODE = 'P0001';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM court_operating_hours h
    WHERE h.court_id    = NEW.court_id
      AND h.day_of_week = v_dow
      AND (v_local_start - v_day_start) >= h.open_time::interval
      AND (v_local_end   - v_day_start) <= h.close_time::interval
  ) THEN
    RAISE EXCEPTION 'OUTSIDE_OPERATING_HOURS' USING ERRCODE = 'P0001';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM court_blackouts b
    WHERE b.court_id = NEW.court_id
      AND tstzrange(b.starts_at, b.ends_at, '[)') && tstzrange(NEW.starts_at, NEW.ends_at, '[)')
  ) THEN
    RAISE EXCEPTION 'COURT_BLACKOUT' USING ERRCODE = 'P0001';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_booking
BEFORE INSERT OR UPDATE ON bookings
FOR EACH ROW EXECUTE FUNCTION fn_validate_booking();


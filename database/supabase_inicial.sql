-- ---------------------------------------------------------------------
-- 9. Disponibilidad de una cancha en un dia (lo usa la API, la cache
--    Redis y el chatbot de IA como "tool")
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_court_availability(p_court_id uuid, p_date date)
RETURNS TABLE (
  slot_start     timestamptz,
  slot_end       timestamptz,
  is_available   boolean,
  price_per_hour numeric,
  is_peak        boolean
)
LANGUAGE sql STABLE AS $$
  WITH c AS (
    SELECT id, slot_minutes
    FROM courts
    WHERE id = p_court_id AND status = 'active'
  ),
  slots AS (
    SELECT
      (ts AT TIME ZONE 'America/Lima')                                     AS s_start,
      ((ts + make_interval(mins => c.slot_minutes)) AT TIME ZONE 'America/Lima') AS s_end,
      ts::time                                                             AS local_time
    FROM c
    JOIN court_operating_hours h
      ON h.court_id = c.id
     AND h.day_of_week = EXTRACT(DOW FROM p_date)
    CROSS JOIN LATERAL generate_series(
      p_date + h.open_time,
      p_date + h.close_time - make_interval(mins => c.slot_minutes),
      make_interval(mins => c.slot_minutes)
    ) AS ts
  )
  SELECT
    s.s_start,
    s.s_end,
    s.s_start > now()
    AND NOT EXISTS (
      SELECT 1 FROM bookings b
      WHERE b.court_id = p_court_id
        AND b.status NOT IN ('cancelled', 'expired')   -- mismo predicado que el EXCLUDE => usa su indice GiST
        AND b.period && tstzrange(s.s_start, s.s_end, '[)')
    )
    AND NOT EXISTS (
      SELECT 1 FROM court_blackouts bl
      WHERE bl.court_id = p_court_id
        AND tstzrange(bl.starts_at, bl.ends_at, '[)') && tstzrange(s.s_start, s.s_end, '[)')
    ) AS is_available,
    pr.price_per_hour + pr.lighting_surcharge,
    COALESCE(pr.is_peak, false)
  FROM slots s
  LEFT JOIN LATERAL (
    SELECT r.price_per_hour, r.lighting_surcharge, r.is_peak
    FROM pricing_rules r
    WHERE r.court_id = p_court_id
      AND r.is_active
      AND (r.day_of_week IS NULL OR r.day_of_week = EXTRACT(DOW FROM p_date))
      AND s.local_time >= r.start_time
      AND s.local_time <  r.end_time
      AND (r.valid_from IS NULL OR r.valid_from <= p_date)
      AND (r.valid_to   IS NULL OR r.valid_to   >= p_date)
    ORDER BY r.priority DESC, r.day_of_week NULLS LAST
    LIMIT 1
  ) pr ON true
  ORDER BY s.s_start;
$$;


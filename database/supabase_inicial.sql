-- ---------------------------------------------------------------------
-- Canchas aprobadas cerca de un punto, ordenadas por distancia (km).
-- Si el punto esta FUERA de Huamanga (ej. alguien abre la web desde Lima)
-- se usa la Plaza de Armas de Huamanga como punto de partida.
-- ---------------------------------------------------------------------
DROP FUNCTION IF EXISTS fn_nearby_venues(numeric, numeric, numeric, sport_type);
CREATE OR REPLACE FUNCTION fn_nearby_venues(
  p_lat numeric,
  p_lng numeric,
  p_radius_km numeric DEFAULT 5,
  p_sport sport_type DEFAULT NULL
)
RETURNS TABLE (
  venue_id          uuid,
  name              varchar,
  slug              varchar,
  district          varchar,
  address           varchar,
  address_reference varchar,
  lat               numeric,
  lng               numeric,
  distance_km       numeric,
  rating_avg        numeric,
  from_center       boolean,
  maps_url          text,
  waze_url          text
)
LANGUAGE sql STABLE AS $$
  WITH origin AS (
    SELECT
      inside,
      CASE WHEN inside THEN p_lat ELSE -13.1588 END AS olat,   -- Plaza de Armas de Huamanga
      CASE WHEN inside THEN p_lng ELSE -74.2239 END AS olng
    FROM (SELECT COALESCE(p_lat BETWEEN -13.60 AND -12.80 AND p_lng BETWEEN -74.75 AND -73.75, false) AS inside) x
  ),
  box AS (
    SELECT o.*, p_radius_km / 111.0 AS dlat, p_radius_km / (111.0 * cos(radians(o.olat))) AS dlng FROM origin o
  ),
  cand AS (
    SELECT v.*, d.name AS district_name, box.inside,
           6371 * 2 * asin(sqrt(
             power(sin(radians(v.lat - box.olat) / 2), 2) +
             cos(radians(box.olat)) * cos(radians(v.lat)) *
             power(sin(radians(v.lng - box.olng) / 2), 2)
           )) AS dist
    FROM venues v
    JOIN districts d ON d.id = v.district_id AND d.is_active
    CROSS JOIN box
    WHERE v.status = 'approved'
      AND v.lat BETWEEN box.olat - box.dlat AND box.olat + box.dlat
      AND v.lng BETWEEN box.olng - box.dlng AND box.olng + box.dlng
      AND (p_sport IS NULL OR EXISTS (
            SELECT 1 FROM courts c
            WHERE c.venue_id = v.id AND c.status = 'active' AND c.sport = p_sport))
  )
  SELECT id, name, slug, district_name, address, address_reference, lat, lng,
         ROUND(dist::numeric, 2), rating_avg, NOT inside,
         'https://www.google.com/maps/dir/?api=1&destination=' || lat || ',' || lng,
         'https://waze.com/ul?ll=' || lat || ',' || lng || '&navigate=yes'
  FROM cand
  WHERE dist <= p_radius_km
  ORDER BY dist;
$$;

-- =====================================================================
--  ReservaYa Ayacucho - 004_seguridad.sql (Row Level Security)
--  En Supabase las tablas de "public" se pueden leer por la API con la
--  clave publica (anon). Activamos RLS en TODAS y solo abrimos lectura
--  del catalogo publico. Reservas, pagos, usuarios e IA solo los toca
